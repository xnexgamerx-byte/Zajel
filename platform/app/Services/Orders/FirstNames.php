    /** كلمةٌ قبل الاسم: «ام علي»، «ابو حسين»، «عبد الله» */
    private const BEFORE = ['ام', 'ابو', 'ابن', 'بنت', 'عبد', 'الحاج', 'حاج', 'الحاجه', 'حجي', 'السيد', 'سيد', 'الشيخ', 'شيخ', 'الست', 'ست'];

    /** @var array<string, true>|null */
    private static ?array $folded = null;

    /** يبدأ السطر باسمٍ أوّل: «زينب كاظم»، «الزهراء قدوتي»، «ام علي» */
    public static function starts(string $line): bool
    {
        $words = array_values(array_filter(explode(' ', Arabic::fold($line))));
        if ($words === []) {
            return false;
        }

        $known = self::$folded ??= array_fill_keys(array_map(fn (string $name) => Arabic::looseFold($name), self::NAMES), true);

        if (in_array($words[0], self::BEFORE, true) && isset($words[1])) {
            return $words[0] === 'عبد' || isset($known[Arabic::looseFold($words[1])]);
        }

        return isset($known[Arabic::looseFold($words[0])]);
    }
